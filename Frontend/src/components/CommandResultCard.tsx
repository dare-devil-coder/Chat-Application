'use client';

import React from 'react';
import { Sparkles, X } from 'lucide-react';
import { CommandResult } from '../lib/commands';

interface CommandResultCardProps {
  result: CommandResult | null;
  loading: boolean;
  onUse: (text: string) => void;
  onClose: () => void;
}

// Private answer to a slash command. Only the person who typed the command sees it.
export const CommandResultCard: React.FC<CommandResultCardProps> = ({
  result,
  loading,
  onUse,
  onClose,
}) => {
  if (!loading && !result) return null;

  return (
    <div className="bg-[#FFFFFF] border-t border-[#E5E7EB] px-6 py-3 max-h-[220px] overflow-y-auto shrink-0">
      <div className="flex items-center gap-2 mb-1">
        <Sparkles size={16} color="#2563EB" />
        <p className="text-[13px] font-medium text-[#111827] flex-1">
          {loading ? 'Thinking...' : result?.title}
        </p>
        <button
          type="button"
          onClick={onClose}
          title="Close"
          aria-label="Close"
          className="w-7 h-7 rounded hover:bg-[#F8FAFC] flex items-center justify-center"
        >
          <X size={15} color="#6B7280" />
        </button>
      </div>

      {!loading && result && (
        <>
          {result.text && (
            <p className="text-[13px] text-[#111827] whitespace-pre-wrap break-words">{result.text}</p>
          )}

          {result.suggestions.length > 0 && (
            <div className="flex flex-wrap gap-2 mt-1">
              {result.suggestions.map((s, i) => (
                <button
                  key={i}
                  type="button"
                  onClick={() => onUse(s)}
                  title="Put this reply in the message box"
                  className="px-3 py-1.5 rounded-full border border-[#E5E7EB] bg-[#F8FAFC] hover:bg-[#EFF6FF] hover:border-[#2563EB] text-[13px] text-[#111827] text-left transition-colors duration-120"
                >
                  {s}
                </button>
              ))}
            </div>
          )}

          {result.use_text && (
            <button
              type="button"
              onClick={() => onUse(result.use_text as string)}
              className="mt-2 h-8 px-3 rounded-lg bg-[#2563EB] hover:bg-[#1D4ED8] text-white text-[13px] font-medium transition-colors duration-120"
            >
              Use this text
            </button>
          )}

          {result.provider && (
            <p className="text-[11px] text-[#9CA3AF] mt-2">
              {result.provider === 'mock'
                ? 'Offline demo mode (no AI key set)'
                : `Generated by AI (${result.provider})`}
            </p>
          )}
        </>
      )}
    </div>
  );
};